def _counts() -> dict:
    """Read-only peek at the findings store; honest zeros when absent."""
    out: dict = {"db": _DB.exists()}
    if not _DB.exists():
        return out
    try:
        conn = sqlite3.connect(f"file:{_DB.as_posix()}?mode=ro", uri=True, timeout=5)
        try:
            out["findings_by_module"] = {
                r[0]: r[1] for r in conn.execute(
                    "SELECT module, COUNT(*) FROM findings GROUP BY module")}
            out["findings_by_status"] = {
                r[0]: r[1] for r in conn.execute(
                    "SELECT status, COUNT(*) FROM findings GROUP BY status")}
            row = conn.execute(
                "SELECT run_id, ts, status FROM runs ORDER BY ts DESC LIMIT 1").fetchone()
            if row:
                out["last_run"] = {"run_id": row[0], "ts": row[1], "status": row[2]}
            out["leads"] = conn.execute(
                "SELECT COUNT(*) FROM findings WHERE kind='lead'").fetchone()[0]
            out["citation_gaps"] = conn.execute(
                "SELECT COUNT(*) FROM findings WHERE kind='citation_gap'").fetchone()[0]
        finally:
            conn.close()
    except sqlite3.Error as e:
        out["db_error"] = str(e)[:120]
    return out


@router.get("/api/research/summary")
def summary(_=Depends(require_owner)):
    reports = {}
    for name, p in _REPORTS.items():
        if p.exists():
            reports[name] = {
                "built": dt.datetime.fromtimestamp(p.stat().st_mtime).isoformat(timespec="seconds"),
                "bytes": p.stat().st_size,
            }
        else:
            reports[name] = None
    return {"ok": True, "reports": reports, "store": _counts()}


@router.get("/api/research/report/{name}")
def report(name: str, _=Depends(require_owner)):
    p = _REPORTS.get(name)
    if p is None:
        raise HTTPException(404, "unknown report")
    if not p.exists():
        return HTMLResponse(
            "<html><body style='font-family:system-ui;padding:2rem;background:#0C0A14;color:#EDF1F6'>"
            f"<h2>{name} report not built yet</h2><p>Run the director CLI in "
            "C:\\Users\\you\\Downloads\\neuron-research to build it.</p></body></html>",
            status_code=200)
    return HTMLResponse(p.read_text(encoding="utf-8"),
                        headers={"Cache-Control": "no-store"})


# -- per-client research & marketing (2026-08-05) -----------------------------------------
# Each GEO lane gets its own niche config (niches/<slug>.json, generated by client_sync from
# the client profile), owner-triggered director runs as tracked jobs, and a weekly cadence
# dial stored ADDITIVELY in the profile (research_cadence - the publishing cadence schema is
# untouched). The hourly Neuron-Research-Cadence task fires due lanes from the repo side.

_SLUG_RE = re.compile(r"^[a-z0-9-]{1,40}$")
_NICHES = _REPO / "niches"
_VIEWS = _REPO / "views"
_RUN_KINDS = ("research_run", "marketing_run")
_STEP_TIMEOUTS = {"run": 2700, "report": 900}


def _check_slug(slug: str) -> None:
    if not _SLUG_RE.match(slug or ""):
        raise HTTPException(400, "bad slug (want [a-z0-9-]{1,40})")


def _lane_profiles() -> dict[str, dict]:
    good, _bad = eng.client_profile.load_all()
    return good


def _require_lane(slug: str) -> dict:
    _check_slug(slug)
    p = _lane_profiles().get(slug)
    if p is None:
        raise HTTPException(404, f"unknown client lane '{slug}'")
    return p


def _ro_conn() -> sqlite3.Connection | None:
    if not _DB.exists():
        return None
    try:
        return sqlite3.connect(f"file:{_DB.as_posix()}?mode=ro", uri=True, timeout=5)
    except sqlite3.Error:
        return None


def _parse_ts(value) -> dt.datetime | None:
    if not value:
        return None
    try:
        return dt.datetime.fromisoformat(str(value)[:19])
    except ValueError:
        return None


def _cadence_view(profile: dict, last_run_ts: str | None) -> dict:
    """Mirror of client_cadence.py's due math so the UI shows the same truth the runner acts on."""
    rc = profile.get("research_cadence") or {}
    try:
        every_weeks = int(rc.get("every_weeks") or 0)
    except (TypeError, ValueError):
        every_weeks = 0
    out = {"every_weeks": every_weeks, "last_auto": rc.get("last_auto"), "next_due": None, "due": False}
    if every_weeks > 0:
        basis = _parse_ts(rc.get("last_auto")) or _parse_ts(last_run_ts)
        if basis is None:
            out["due"] = True  # never ran -> due at the next hourly check
        else:
            nxt = basis + dt.timedelta(weeks=every_weeks)
            out["next_due"] = nxt.isoformat(timespec="seconds")
            out["due"] = dt.datetime.now() >= nxt
    return out


def _lane_state(slug: str, profile: dict, conn: sqlite3.Connection | None) -> dict:
    last_run = None
    findings: dict[str, int] = {}
    if conn is not None:
        try:
            row = conn.execute(
                "SELECT run_id, ts, status FROM runs WHERE niche=? ORDER BY ts DESC LIMIT 1",
                (slug,)).fetchone()
            if row:
                last_run = {"run_id": row[0], "ts": row[1], "status": row[2]}
            findings = {r[0]: r[1] for r in conn.execute(
                "SELECT status, COUNT(*) FROM findings WHERE niche=? GROUP BY status", (slug,))}
        except sqlite3.Error:
            pass
    niche_path = _NICHES / f"{slug}.json"
    # The site the directors actually look at. It lives in the NICHE, not the lane profile:
    # m1_competitor and marketing/s1_found both read cfg["brand"]["domain"], and placements
    # excludes it from its own target list. Falls back to the profile's domain as a SUGGESTION
    # so the field is never blank, and says which one it is - an operator has to be able to tell
    # "this is what will be researched" from "this is what we would default to".
    website, website_source = "", ""
    if niche_path.is_file():
        try:
            website = ((json.loads(niche_path.read_text(encoding="utf-8")) or {})
                       .get("brand") or {}).get("domain", "") or ""
            website_source = "niche" if website else ""
        except (OSError, json.JSONDecodeError):
            pass
    if not website:
        website = (profile.get("brand") or {}).get("domain", "") or ""
        website_source = "profile" if website else ""
    return {
        "slug": slug,
        "name": (profile.get("brand") or {}).get("name", slug),
        "niche_exists": niche_path.is_file(),
        "website": website,
        "website_source": website_source,
        "last_run": last_run,
        "findings_by_status": findings,
        "cadence": _cadence_view(profile, (last_run or {}).get("ts")),
        "report_built": (_VIEWS / f"{slug}.html").is_file(),
        "job_id": JOBS.running_for(slug, kinds=_RUN_KINDS),
    }


@router.get("/api/research/clients")
def research_clients(_=Depends(require_owner)):
    conn = _ro_conn()
    try:
        lanes = [_lane_state(slug, p, conn) for slug, p in sorted(_lane_profiles().items())]
    finally:
        if conn is not None:
            conn.close()
    return {"ok": True, "clients": lanes, "db": _DB.exists()}


def _run_step(cmd: list[str], timeout: int) -> dict:
    """One subprocess step of a job (cwd = the research repo, utf-8 forced)."""
    env = {**os.environ, "PYTHONIOENCODING": "utf-8"}
    try:
        r = subprocess.run(cmd, cwd=str(_REPO), capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=timeout, env=env)
        out = (r.stdout or "").strip()
        tail = "\n".join(out.splitlines()[-6:])
        return {"cmd": " ".join(cmd[1:]), "exit": r.returncode, "tail": tail[:1500],
                "stdout": out[-20000:], "stderr": (r.stderr or "").strip()[-500:]}
    except subprocess.TimeoutExpired:
        return {"cmd": " ".join(cmd[1:]), "exit": -1, "tail": "", "stdout": "",
                "stderr": f"timed out after {timeout}s"}


@router.post("/api/research/clients/{slug}/sync")
def research_client_sync(slug: str, _=Depends(require_owner)):
    """Generate/refresh niches/<slug>.json from the lane profile (merge - hand-edits kept)."""
    _require_lane(slug)
    step = _run_step([sys.executable, str(_REPO / "engine" / "client_sync.py"), "--slug", slug], 120)
    out = None
    try:
        raw = step.get("stdout") or ""
        # client_sync prints one JSON object; slice it out even with warnings around it
        out = json.loads(raw[raw.index("{"):raw.rindex("}") + 1]) if "{" in raw else None
    except (ValueError, json.JSONDecodeError):
        out = None
    if step["exit"] != 0 or out is None or not out.get("ok"):
        detail = (out or {}).get("errors") or step["stderr"] or step["tail"] or "client_sync failed"
        raise HTTPException(502, f"sync failed: {json.dumps(detail)[:400]}")
    summary = (out.get("synced") or [{}])[0]
    summary["niche_exists"] = (_NICHES / f"{slug}.json").is_file()
    return {"ok": True, "niche": summary}


class ResearchWebsiteBody(BaseModel):
    website: str


def _norm_website(value: str) -> str:
    """Bare lowercase host: scheme, path and a leading www. removed.

    ⛔ MATCHES neuron-research engine/marketing/s3_booked.py::_norm_domain ON PURPOSE. That is
    the shape the repo already stores and compares against (placements.py checks
    `host == brand_domain`), so a value normalized any other way would silently stop matching.
    Kept as a copy rather than an import because the original is a private helper inside a
    marketing stage module - importing it would drag that module's imports into the cockpit.
    """
    from urllib.parse import urlparse
    v = (value or "").strip()
    if not v:
        return ""
    try:
        u = urlparse(v if "://" in v else "https://" + v)
        host = (u.netloc or u.path.split("/")[0]).lower()
    except ValueError:
        return ""
    host = host.split("@")[-1].split(":")[0].strip().strip(".")
    return host[4:] if host.startswith("www.") else host


_HOST_RE = re.compile(r"^(?=.{4,253}$)[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?"
                      r"(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$")


@router.post("/api/research/clients/{slug}/website")
def research_client_website(slug: str, body: ResearchWebsiteBody, _=Depends(require_owner)):
    """Set the site the research + marketing directors look at (niche brand.domain).

    Creates the niche config first when there is none, so an operator can point a lane at a site
    in one action instead of having to know that Sync must come first. Everything else in the
    niche is preserved - this only ever rewrites brand.domain, and client_sync's merge law then
    keeps it across re-syncs (existing keys win).
    """
    _require_lane(slug)
    host = _norm_website(body.website)
    if not host or not _HOST_RE.match(host):
        raise HTTPException(400, "that does not look like a website (want e.g. example.com)")

    path = _NICHES / f"{slug}.json"
    created = False
    if not path.is_file():
        # No niche yet: build it from the profile exactly as the Sync button does, then point it.
        research_client_sync(slug)          # raises HTTPException on failure
        created = True
    try:
        niche = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        raise HTTPException(502, f"could not read the niche config: {str(e)[:160]}")
    if not isinstance(niche, dict):
        raise HTTPException(502, "the niche config is not a JSON object; refusing to write it")
    brand = dict(niche.get("brand") or {})
    was = brand.get("domain", "")
    brand["domain"] = host
    # engine/config.py validates brand{name,domain}; a niche with no name would fail a run, so
    # fill it from the profile rather than writing a config the director will reject.
    if not brand.get("name"):
        brand["name"] = (_lane_profiles().get(slug, {}).get("brand") or {}).get("name") or slug
    niche["brand"] = brand
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(niche, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
    tmp.replace(path)
    return {"ok": True, "website": host, "was": was, "niche_created": created,
            "niche_exists": True}


class ResearchRunBody(BaseModel):
    kind: str = "research"   # research | marketing


@router.post("/api/research/clients/{slug}/run")
def research_client_run(slug: str, body: ResearchRunBody, _=Depends(require_owner)):
    """Queue a director run for this lane as a tracked background job."""
    _require_lane(slug)
    kind = (body.kind or "").strip().lower()
    if kind not in ("research", "marketing"):
        raise HTTPException(400, "kind must be 'research' or 'marketing'")
    if not (_NICHES / f"{slug}.json").is_file():
        raise HTTPException(400, "no niche config for this client yet - sync first")
    existing = JOBS.running_for(slug, kinds=_RUN_KINDS)
    if existing:
        return {"job_id": existing, "status": "running", "already_running": True}

    py = sys.executable
    if kind == "research":
        job_kind = "research_run"
        main_cmd = [py, str(_REPO / "engine" / "director.py"), "--niche", slug, "--modules", "m3,m1"]
        report_cmd = [py, str(_REPO / "engine" / "director.py"), "--niche", slug, "--report"]
        label = "research modules m3,m1"
    else:
        job_kind = "marketing_run"
        main_cmd = [py, str(_REPO / "engine" / "marketing_director.py"), "--niche", slug,
                    "--run", "--stages", "s1"]
        report_cmd = [py, str(_REPO / "engine" / "marketing_director.py"), "--niche", slug, "--report"]
        label = "marketing stage s1"

    def _job(progress):
        progress(phase="run", pct=10, log_line=f"{slug}: running {label} (subprocess)...")
        main = _run_step(main_cmd, _STEP_TIMEOUTS["run"])
        # director exit 1 = partial (fail-soft modules; a runs row exists) - honest but not fatal
        if main["exit"] not in (0, 1):
            raise RuntimeError(f"{label} failed (exit {main['exit']}): "
                               f"{(main['stderr'] or main['tail'])[:300]}")
        progress(phase="report", pct=70,
                 log_line=f"{slug}: {label} done (exit {main['exit']}); building the report...")
        rep = _run_step(report_cmd, _STEP_TIMEOUTS["report"])
        progress(pct=95, log_line=f"{slug}: report step exit {rep['exit']}")
        steps = [{k: v for k, v in s.items() if k != "stdout"} for s in (main, rep)]
        return {"ok": True, "kind": kind, "slug": slug, "partial": main["exit"] == 1,
                "steps": steps}

    job_id = JOBS.enqueue_fn(job_kind, slug, _job, params={"kind": kind})
    return {"job_id": job_id, "status": "queued"}


class ResearchCadenceBody(BaseModel):
    every_weeks: int   # 0 = off


@router.get("/api/research/clients/{slug}/cadence")
def research_cadence_get(slug: str, _=Depends(require_owner)):
    profile = _require_lane(slug)
    conn = _ro_conn()
    last_ts = None
    if conn is not None:
        try:
            row = conn.execute("SELECT ts FROM runs WHERE niche=? ORDER BY ts DESC LIMIT 1",
                               (slug,)).fetchone()
            last_ts = row[0] if row else None
        except sqlite3.Error:
            pass
        finally:
            conn.close()
    return {"slug": slug, "cadence": _cadence_view(profile, last_ts)}


@router.post("/api/research/clients/{slug}/cadence")
def research_cadence_set(slug: str, body: ResearchCadenceBody, _=Depends(require_owner)):
    _require_lane(slug)
    try:
        out = csvc.set_research_cadence(slug, body.every_weeks)
    except ValueError as e:
        raise HTTPException(400, str(e))
    return {"ok": True, **out}



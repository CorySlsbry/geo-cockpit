"""research.py - the cockpit's window into the neuron-research systems (2026-08-04).

Surfaces the two directors' one-page reports (Market Research + AI Marketing Engine)
inside the cockpit, and (2026-08-05) runs them PER CLIENT: each GEO lane gets a niche
config generated from its profile (client_sync), owner-triggered research/marketing
runs as tracked background jobs, an additive research cadence dial, and a per-client
report. Findings approval still happens via the repo CLIs - nothing here approves or
sends anything.

GET  /api/research/summary                     -> live counts from research.db + report freshness
GET  /api/research/report/{name}               -> the report HTML (name: research | marketing)
GET  /api/research/clients                     -> per-lane niche/run/findings/cadence state
POST /api/research/clients/{slug}/sync         -> generate/refresh niches/<slug>.json from the profile
POST /api/research/clients/{slug}/run          -> {kind: research|marketing} as a background job
GET/POST /api/research/clients/{slug}/cadence  -> additive research_cadence {every_weeks, 0=off}
GET  /api/research/client-report/{slug}        -> views/<slug>.html (honest not-built page otherwise)
"""
